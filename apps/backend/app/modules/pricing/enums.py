"""Перечисления ценообразования."""

from __future__ import annotations

from enum import StrEnum


class PricingType(StrEnum):
    """Как товар показывает цену на витрине.

    ON_REQUEST — отдельный тип, а не цена 0. Ноль означал бы "бесплатно",
    участвовал бы в сортировке по возрастанию цены и в подсчёте суммы
    заявки. Отсутствие цены — это состояние, а не число.
    """

    FIXED = "FIXED"  # одна цена
    FROM = "FROM"  # "от 2 600 ₸" — минимальная из ступеней
    TIERED = "TIERED"  # таблица ступеней по количеству
    ON_REQUEST = "ON_REQUEST"  # цены нет, кнопка "Запросить цену"
